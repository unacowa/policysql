// The only `POLICYSQL_*` code -> HTTP status table (ADR 0019, ADR 0023). The public
// specification is the source of truth: the table in website/api/errors.md. A test checks
// that this table equals its library section, and that every code the library source (TypeScript and Rust)
// can produce has an entry. Engine operations return codes; only the HTTP adapter turns a
// code into a status.

export const ERROR_STATUS: Readonly<Record<string, number>> = Object.freeze({
  // Malformed request, SQL, or parameter.
  POLICYSQL_INVALID_REQUEST: 400,
  POLICYSQL_INVALID_SQL: 400,
  POLICYSQL_MULTIPLE_STATEMENTS: 400,
  POLICYSQL_UNSUPPORTED_SQL: 400,
  POLICYSQL_DUPLICATE_RESULT_COLUMN: 400,
  POLICYSQL_INVALID_PARAMETER: 400,
  POLICYSQL_AMBIGUOUS_PARAMETER_TYPE: 400,
  POLICYSQL_RESERVED_PARAMETER: 400,
  POLICYSQL_IDEMPOTENCY_KEY_REQUIRED: 400,
  // Denied by session, policy, or deployment.
  POLICYSQL_FORBIDDEN_ACCESS: 403,
  POLICYSQL_MISSING_POLICY: 403,
  POLICYSQL_FORBIDDEN_OPERATION: 403,
  POLICYSQL_FORBIDDEN_COLUMN: 403,
  POLICYSQL_FORBIDDEN_COLUMN_CONTEXT: 403,
  POLICYSQL_PRESET_COLUMN: 403,
  POLICYSQL_TRANSACTION_MODE_VIOLATION: 403,
  POLICYSQL_DATABASE_BINDING_REJECTED: 403,
  POLICYSQL_COST_UNKNOWN: 403,
  POLICYSQL_NOT_FOUND: 404,
  // State conflicts.
  POLICYSQL_STALE_OPERATION: 409,
  POLICYSQL_IDEMPOTENCY_CONFLICT: 409,
  POLICYSQL_TRANSACTION_CONFLICT: 409,
  POLICYSQL_TRANSACTION_UNAVAILABLE: 409,
  POLICYSQL_COMMIT_CHECK_REJECTED: 409,
  POLICYSQL_LIMIT_EXCEEDED: 413,
  POLICYSQL_REQUEST_TOO_LARGE: 413,
  POLICYSQL_UNSUPPORTED_MEDIA_TYPE: 415,
  POLICYSQL_EXPECTATION_FAILED: 422,
  POLICYSQL_SCHEMA_MISMATCH: 422,
  POLICYSQL_TRANSACTION_LIMIT_EXCEEDED: 429,
  POLICYSQL_USAGE_BUDGET_EXCEEDED: 429,
  POLICYSQL_INTERNAL: 500,
  POLICYSQL_DATABASE_REQUIRED: 500,
  POLICYSQL_DATABASE_UNAVAILABLE: 503,
  POLICYSQL_COST_ADMISSION_UNAVAILABLE: 503,
  POLICYSQL_TIMEOUT: 504,
  POLICYSQL_DATABASE_TIMEOUT: 504,
});

/** The status for a code. A code outside the table is a library fault and is served as 500. */
export const statusFor = (code: string): number =>
  typeof code === "string" && Object.hasOwn(ERROR_STATUS, code) ? ERROR_STATUS[code] : 500;
